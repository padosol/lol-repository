-- riot 스키마 초기 구조 — lol-repository 가 소유하는 마이그레이션 체인의 시작.
--
-- 공유 저장소 lol-db-schema V1~V35 를 적용한 결과에서 riot 객체만 옮겼다
-- (테이블 50 · 독립 시퀀스 3 · 뷰 6 + 기준 데이터 item_meta). member·community·duo 등 앱 테이블은 lol-server 소유라 없다.
-- 스키마 이름은 쓰지 않는다 — Flyway(spring.flyway.default-schema=riot)가 search_path 로 정한다.
-- 이후 변경은 이 디렉터리에 V2 부터 추가한다.

-- esports_roster 의 EXCLUDE 제약(gist)이 쓴다. 확장은 public 에 둔다.
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;

