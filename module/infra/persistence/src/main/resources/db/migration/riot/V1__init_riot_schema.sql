CREATE VIEW v_esports_stage_progress AS
 SELECT st.season_id,
    st.stage_key,
    st.name,
    count(m.match_id) AS matches,
    count(*) FILTER (WHERE ((m.status)::text = 'COMPLETED'::text)) AS completed,
    COALESCE(sum((m.home_score + m.away_score)), (0)::bigint) AS games,
    ( SELECT count(*) AS count
           FROM ( SELECT x.home_team_id AS team_id
                   FROM esports_match x
                  WHERE (x.stage_id = st.stage_id)
                UNION
                 SELECT x.away_team_id
                   FROM esports_match x
                  WHERE (x.stage_id = st.stage_id)) u) AS teams
   FROM (esports_stage st
     LEFT JOIN esports_match m ON ((m.stage_id = st.stage_id)))
  GROUP BY st.season_id, st.stage_id, st.stage_key, st.name, st.sort_order
  ORDER BY st.sort_order;

COMMENT ON VIEW v_esports_stage_progress IS '스테이지별 입력 진행률. 예상 매치 수(1~2R 90 / 3~5R 60)와 대조한다';

