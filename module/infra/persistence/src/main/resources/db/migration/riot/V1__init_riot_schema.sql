CREATE VIEW v_esports_match_invalid AS
 SELECT m.match_id,
    m.match_date,
    st.name AS stage,
    h.team_code AS home,
    a.team_code AS away,
    m.home_score,
    m.away_score,
    m.best_of,
    count(g.game_id) AS game_rows,
    count(*) FILTER (WHERE ((g.winner_team_id)::text = (m.home_team_id)::text)) AS home_game_wins,
    count(*) FILTER (WHERE ((g.winner_team_id)::text = (m.away_team_id)::text)) AS away_game_wins
   FROM ((((esports_match m
     JOIN esports_stage st ON ((st.stage_id = m.stage_id)))
     JOIN esports_team h ON (((h.team_id)::text = (m.home_team_id)::text)))
     JOIN esports_team a ON (((a.team_id)::text = (m.away_team_id)::text)))
     LEFT JOIN esports_game g ON ((g.match_id = m.match_id)))
  WHERE ((m.status)::text = 'COMPLETED'::text)
  GROUP BY m.match_id, m.match_date, st.name, h.team_code, a.team_code, m.home_score, m.away_score, m.best_of
 HAVING ((count(g.game_id) <> (m.home_score + m.away_score)) OR (count(*) FILTER (WHERE ((g.winner_team_id)::text = (m.home_team_id)::text)) <> m.home_score) OR (count(*) FILTER (WHERE ((g.winner_team_id)::text = (m.away_team_id)::text)) <> m.away_score) OR ((m.best_of IS NOT NULL) AND (GREATEST(m.home_score, m.away_score) <> ((m.best_of / 2) + 1))) OR ((m.best_of IS NOT NULL) AND ((m.home_score + m.away_score) > m.best_of)));

COMMENT ON VIEW v_esports_match_invalid IS '오입력 매치 검출. 집계 전 반드시 0행이어야 한다';

CREATE VIEW v_esports_score_zerosum AS
 SELECT st.season_id,
    st.standing_key,
    sum(
        CASE
            WHEN ((m.home_team_id)::text = (t.team_id)::text) THEN (m.home_score - m.away_score)
            ELSE (m.away_score - m.home_score)
        END) AS score_sum
   FROM ((esports_stage st
     JOIN esports_match m ON (((m.stage_id = st.stage_id) AND ((m.status)::text = 'COMPLETED'::text))))
     JOIN esports_team t ON ((((t.team_id)::text = (m.home_team_id)::text) OR ((t.team_id)::text = (m.away_team_id)::text))))
  WHERE (st.standing_key IS NOT NULL)
  GROUP BY st.season_id, st.standing_key;

COMMENT ON VIEW v_esports_score_zerosum IS '세트 득실 제로섬 검증. score_sum 이 0 이 아니면 세트 점수 오입력이 있다';

CREATE VIEW v_esports_season_roster AS
 SELECT s.season_id,
